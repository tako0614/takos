// Regenerates src/contracts/public/route-inventory.ts from the composed
// apiRouter. The inventory is the machine-readable list docs.takos.jp is
// checked against (takos-control docs-shape.json, R2): an endpoint that is
// not here is not a public route, and docs must not describe it.
//
//   bun scripts/generate-route-inventory.mjs
//
// route-inventory.test.ts asserts the checked-in file matches this output,
// so a route change without a regeneration fails the gate.

import { createApiRouter } from "../src/worker/server/routes/api.ts";
import { writeFileSync } from "node:fs";

const noop = async (_c, next) => next();
const router = createApiRouter({ requireAuth: noop, optionalAuth: noop });

const paths = [
  ...new Set(
    router.routes
      .map((route) => route.path)
      .filter((path) => path !== "*" && !path.endsWith("*")),
  ),
]
  .map((path) => "/api" + path)
  .sort();

const HEADER =
  "// Generated by scripts/generate-route-inventory.mjs — do not edit by hand.\n" +
  "// Every public /api route the composed apiRouter serves, one entry per path.\n" +
  "// docs.takos.jp is gated against this list (takos-control docs-shape R2):\n" +
  "// a path documented but absent here does not exist, and a route added to the\n" +
  "// router without regenerating this file fails route-inventory.test.ts.\n\n";

const body =
  HEADER +
  "export const TAKOS_API_ROUTE_INVENTORY: readonly string[] = [\n" +
  paths.map((p) => '  "' + p + '",').join("\n") +
  "\n];\n";

writeFileSync("src/contracts/public/route-inventory.ts", body);
console.log("wrote " + paths.length + " routes");
